USE UNSALDB;

SELECT TOP 5 'BIRIMLEREX' AS Tablo, b.IND, b.STOKNO, s.MALINCINSI, b.BIRIMADI, b.SATISFIYATI1, b.ESKIFIYAT1,
  b.SATISFIYATI, b.ESKISATISFIYATI, b.FIYATDEGISMETARIHI1, b.SATISFIYATIDEGISMETARIHI, s.GUNCELLEMETARIHI
FROM dbo.F0101TBLBIRIMLEREX b
JOIN dbo.F0101TBLSTOKLAR s ON s.IND = b.STOKNO
ORDER BY b.FIYATDEGISMETARIHI1 DESC;

SELECT TOP 5 'STOKLAR' AS Tablo, IND, MALINCINSI, STOKKODU, ANABIRIM, KDVGRUBU, AKTIF, STATUS, YAZARKASA,
  KARTINACILMATARIHI, GUNCELLEMETARIHI
FROM dbo.F0101TBLSTOKLAR
ORDER BY GUNCELLEMETARIHI DESC;

SELECT TOP 5 'STOKLAR_YENI' AS Tablo, IND, MALINCINSI, STOKKODU, ANABIRIM, KDVGRUBU, AKTIF, STATUS, YAZARKASA,
  KARTINACILMATARIHI, GUNCELLEMETARIHI
FROM dbo.F0101TBLSTOKLAR
ORDER BY IND DESC;

SELECT TOP 5 'FASTERSTOKLAR' AS Tablo, IND, STOKNO, BIRIMIND, MALINCINSI, SATISFIYATI1, SUBEIND, SUBEADI,
  FIYATDEGISMETARIHI1, FIYATGUNCELLEMETARIHI, STATUS
FROM dbo.TBLFASTERSTOKLAR
ORDER BY FIYATGUNCELLEMETARIHI DESC;

SELECT TOP 8 'FASTERLOG' AS Tablo, * FROM dbo.TBLFASTERLOG ORDER BY 2 DESC;

SELECT TOP 8 'LOG' AS Tablo, * FROM dbo.TBLLOG ORDER BY 2 DESC;
