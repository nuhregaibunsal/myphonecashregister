USE UNSALDB;
SET NOCOUNT ON;

SELECT (
  SELECT
    (SELECT COUNT(*) FROM (SELECT b.STOKNO FROM dbo.F0101TBLBIRIMLEREX b GROUP BY b.STOKNO HAVING COUNT(*) > 1) x) AS cokBirimliUrunSayisi,
    JSON_QUERY((
      SELECT TOP 12 s.IND, s.MALINCINSI, s.STOKKODU, s.ANABIRIM AS anaBirimInd,
        JSON_QUERY((
          SELECT b.IND, b.BIRIMADI, b.CARPAN, b.AGIRLIK, b.BARCODE, b.BARCODESTD, b.SATISFIYATI1, b.ESKIFIYAT1,
            b.FIYATDEGISMETARIHI1, b.ANABIRIM, b.VARSAYILAN, b.ACIKLAMA, b.ACIKLAMA2, b.KDV, b.KDVDAHIL
          FROM dbo.F0101TBLBIRIMLEREX b
          WHERE b.STOKNO = s.IND
          ORDER BY b.IND
          FOR JSON PATH, INCLUDE_NULL_VALUES
        )) AS birimler
      FROM dbo.F0101TBLSTOKLAR s
      WHERE (SELECT COUNT(*) FROM dbo.F0101TBLBIRIMLEREX b WHERE b.STOKNO = s.IND) > 1
      ORDER BY s.IND DESC
      FOR JSON PATH, INCLUDE_NULL_VALUES
    )) AS ornekler
  FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
) AS KopyalaYapistir;
